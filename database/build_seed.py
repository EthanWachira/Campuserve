    preds.append(f"({tid}, {pred_cat+1}, {conf}, 'linear_svm_calibrated-seed', {(cur_cat+1) if reviewed else 'NULL'}, {ago(age_min)})")

    if assignee:
        updates.append(f"({tid}, {assignee}, {q('Ticket assigned to ' + uname[assignee] + '.')}, 'open', 'assigned', 0, {ago(age_min - 45)})")
        notes.append(f"({student}, {q('Your request ' + ref + ' was assigned')}, {q('Assigned to ' + uname[assignee] + '.')}, {q('?r=tickets/show&id=' + str(tid))}, {1 if status in ('closed','resolved') else random.choice([0,1])}, {ago(age_min - 45)})")
    if wrong and reviewed and assignee:
        updates.append(f"({tid}, {assignee}, {q('Category corrected from ' + CAT_NAMES[pred_cat] + ' to ' + CAT_NAMES[cat] + '.')}, NULL, NULL, 1, {ago(age_min - 50)})")
    if status in ("in_progress", "resolved", "closed"):
        updates.append(f"({tid}, {assignee}, {q('We are looking into this and will update you shortly.')}, 'assigned', 'in_progress', 0, {ago(age_min - 180)})")
    if status in ("resolved", "closed"):
        msgs = ["This has been fixed. Please check and reply if the problem continues.",
                "Your request has been completed. The details were sent to your student email.",
                "We have updated your record. Thank you for your patience."]
        updates.append(f"({tid}, {assignee}, {q(random.choice(msgs))}, 'in_progress', 'resolved', 0, {ago(max(resolved_age, 5))})")
        notes.append(f"({student}, {q('Your request ' + ref + ' was resolved')}, NULL, {q('?r=tickets/show&id=' + str(tid))}, 1, {ago(max(resolved_age, 5))})")
    if status == "closed":
        updates.append(f"({tid}, {student}, {q('Thanks, this is sorted.')}, 'resolved', 'closed', 0, {ago(max(resolved_age, 5) - 600)})")

