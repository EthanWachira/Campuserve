    reviewed = status != "open"
    # Open tickets keep the model's category until a human looks; others were corrected if the model was wrong.
    cur_cat = pred_cat if not reviewed else cat
    needs_review = 1 if (not reviewed and conf < 0.45) else 0
    src = "ml"
    assignee = random.choice(staff_ids[cur_cat + 1]) if status != "open" else None
