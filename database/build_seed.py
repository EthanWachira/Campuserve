# ---- tickets
HIGH_WORDS = ("urgent", "harass", "safety", "unsafe", "exam", "emergency", "deadline", "locked")
MED_WORDS = ("clash", "missing", "wrong", "blocked", "cannot", "not working", "overdue", "twice", "expired")


def priority(text):
    t = text.lower()
    if any(w in t for w in HIGH_WORDS):
        return "high"
    if any(w in t for w in MED_WORDS):
        return "medium"
    return "low"


statuses = ["open"] * 8 + ["assigned"] * 6 + ["in_progress"] * 9 + ["resolved"] * 12 + ["closed"] * 13
random.shuffle(statuses)
weights = [5, 4, 5, 4, 3, 3, 2, 3, 3]        # IT, records, fees, timetable, admissions, library, welfare, facilities, advising
